def test_main_create_all_then_stamp_head_is_consistent(tmp_path):
    """The SQLite fast-path (`create_all`) + `alembic stamp head` leaves a DB
    Alembic considers current, with no drift against the baseline."""
    url = f"sqlite:///{tmp_path / 'main.db'}"
    eng = create_engine(url)
    try:
        Base.metadata.create_all(eng)
    finally:
        eng.dispose()
    cfg = _config("main", url)
    command.stamp(cfg, "head")

    # No pending migrations and no model↔migration drift.
    script = ScriptDirectory.from_config(cfg)
    head = script.get_current_head()
    eng = create_engine(url)
    try:
        with eng.connect() as conn:
            current = MigrationContext.configure(conn).get_current_revision()
    finally:
        eng.dispose()
    assert current == head
    assert _autogen_diff(Base.metadata, url) == []
