"""Alembic baseline migrations build/teardown the full schema for all three
databases, and stay drift-free against the live SQLAlchemy metadata.

CI is SQLite-only (D6); Postgres is exercised manually. The baseline
migrations are autogenerated from the same metadata ``create_all`` uses, so
``upgrade head`` must reproduce every managed table and ``downgrade base``
must drop them all.
"""

from __future__ import annotations

from pathlib import Path

from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.script import ScriptDirectory
from sqlalchemy import create_engine, inspect

from core.database.identity import IdentityBase
from core.database.models import Base
from core.database.serving_models import ServingBase

_REPO_ROOT = Path(__file__).resolve().parents[1]
_INI = _REPO_ROOT / "alembic.ini"


def _config(name: str, url: str) -> Config:
    cfg = Config(str(_INI), ini_section=name)
    cfg.set_main_option("sqlalchemy.url", url)
    return cfg


def _table_names(url: str) -> set[str]:
    eng = create_engine(url)
    try:
        return set(inspect(eng).get_table_names())
    finally:
        eng.dispose()


def _managed(metadata) -> set[str]:
    return set(metadata.tables)


def test_main_upgrade_head_creates_all_tables(tmp_path):
    url = f"sqlite:///{tmp_path / 'main.db'}"
    command.upgrade(_config("main", url), "head")
    present = _table_names(url)
    assert _managed(Base.metadata) <= present


def test_identity_upgrade_head_creates_all_tables(tmp_path):
    url = f"sqlite:///{tmp_path / 'identity.db'}"
    command.upgrade(_config("identity", url), "head")
