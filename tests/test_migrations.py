def _autogen_diff(metadata, url: str):
    eng = create_engine(url)
    try:
        with eng.connect() as conn:
            ctx = MigrationContext.configure(
                conn, opts={"compare_type": True, "target_metadata": metadata}
            )
            return compare_metadata(ctx, metadata)
    finally:
        eng.dispose()


def test_main_create_all_matches_migration_head(tmp_path):
    """No drift: a fresh `upgrade head` leaves an empty autogen diff."""
    url = f"sqlite:///{tmp_path / 'main.db'}"
    command.upgrade(_config("main", url), "head")
    assert _autogen_diff(Base.metadata, url) == []


