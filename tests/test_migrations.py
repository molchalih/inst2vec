def test_main_downgrade_base_drops_all_tables(tmp_path):
    url = f"sqlite:///{tmp_path / 'main.db'}"
    cfg = _config("main", url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    remaining = _table_names(url) - {"alembic_version"}
    assert remaining.isdisjoint(_managed(Base.metadata))


